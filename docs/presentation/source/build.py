def pic(slide, name, path, ph=None):
    """Картинка в плейсхолдер; позиция слайда сохраняется (insert_picture берёт позицию макета)."""
    ph = ph or [s for s in slide.placeholders if s.name == name][0]
    geo = (ph.left, ph.top, ph.width, ph.height)
    p = ph.insert_picture(f'{IMG}/{path}')
    p.left, p.top, p.width, p.height = geo
    return p


def nobullet(*shapes):
    for sh in shapes:
        for p in sh.text_frame._txBody.findall(qn('a:p')):
            ppr = p.find(qn('a:pPr'))
            if ppr is None:
                ppr = etree.Element(qn('a:pPr'))
                p.insert(0, ppr)
            for c in list(ppr):
                if c.tag in (qn('a:buNone'), qn('a:buChar'), qn('a:buAutoNum'), qn('a:buFont')):
                    ppr.remove(c)
            ppr.set('marL', '0')
            ppr.set('indent', '0')
            bn = etree.Element(qn('a:buNone'))
            dr = ppr.find(qn('a:defRPr'))
            if dr is not None:
                dr.addprevious(bn)
            else:
                ppr.append(bn)


# Подсказки «Образец текста» в макетах LibreOffice выводит в PDF — очищаем их
