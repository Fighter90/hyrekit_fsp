def title(slide, text, pill=None, name='Заголовок 13'):
    t = shapes_by_name(slide, name)[0]
    fill(t, text)
    if pill is not None:
        p = at(slide, 0.37, 0.35)
        p.width = Inches(max(2.2, 0.205 * len(text) + 0.75))
        t.width = max(t.width, p.width - Inches(0.3))


def by(slide, name, i=0):
    return shapes_by_name(slide, name)[i]


